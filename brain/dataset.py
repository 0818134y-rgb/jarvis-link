PREFIXES = ["", "", "", "ジャーヴィス、", "ねえ", "ジャービス ", "ちょっと"]
SUFFIXES_IMPERATIVE = ["", "", "ください", "くれる", "もらえる", "くれ", "お願い"]


def expand(template: str, limit: int, rng: random.Random) -> list[str]:
    keys = [k for k in SLOTS if "{" + k + "}" in template]
    if not keys:
        return [template]
    combos = list(itertools.product(*[SLOTS[k] for k in keys]))
    rng.shuffle(combos)
    out = []
    for combo in combos[:limit]:
        s = template
        for k, v in zip(keys, combo):
            s = s.replace("{" + k + "}", v, 1)
        out.append(s)
    return out


def augment(s: str, rng: random.Random) -> str:
    s = rng.choice(PREFIXES) + s
    if s.endswith("て") and rng.random() < 0.5:
        s += rng.choice(SUFFIXES_IMPERATIVE)
    if rng.random() < 0.3:
        s += rng.choice(["？", "?", "。", "！", ""])
    return s


def build(seed: int = 7, per_template: int = 6, aug_copies: int = 2) -> list[tuple[str, str]]:
    rng = random.Random(seed)
    data = []
    for intent, templates in INTENTS.items():
        for t in templates:
            for s in expand(t, per_template, rng):
                data.append((s, intent))
                for _ in range(aug_copies):
                    data.append((augment(s, rng), intent))
    rng.shuffle(data)
    return data


